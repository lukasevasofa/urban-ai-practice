cells = [nbformat.v4.new_markdown_cell(intro)]
source = (DATA / "research_pipeline.py").read_text()
for section in source.split("# %% ")[1:]:
    title, code = section.split("\n", 1)
    cells.extend([nbformat.v4.new_markdown_cell("## " + title), nbformat.v4.new_code_cell(code.strip())])
cells.append(nbformat.v4.new_markdown_cell("""## Повторное использование

`blocks_results.geojson` / CSV — все показатели; `schools.geojson` / CSV — каталог и источники мощности;
`travel_time_minutes.csv` — минуты, строки и столбцы совпадают с `block_id` 0…297.
`practice3/` содержит согласованные кварталы с населением и мощностью, матрицу, параметры,
исходную обеспеченность и неудовлетворённый спрос. Сценарии 600 или 300+300 мест здесь ещё не рассчитываются.
`dashboard.html` создаётся отдельным `generate_dashboard.py` без повторного выполнения анализа.
Картографическая подложка и библиотеки HTML требуют интернет. Геометрия и показатели встроены в файл.
"""))
notebook = nbformat.v4.new_notebook(cells=cells, metadata={"kernelspec": {
    "name": "python3", "language": "python", "display_name": "Python 3.12 (.venv)"}})
nbformat.write(notebook, path)
try:
    NotebookClient(notebook, timeout=1200, resources={"metadata": {"path": str(DATA)}}).execute()
finally:
    nbformat.write(notebook, path)
for cell in notebook.cells:
    for output in cell.get("outputs", []):
        if output.output_type == "stream" and output.name == "stdout":
            print(output.text)
print("Ноутбук выполнен:", path)
